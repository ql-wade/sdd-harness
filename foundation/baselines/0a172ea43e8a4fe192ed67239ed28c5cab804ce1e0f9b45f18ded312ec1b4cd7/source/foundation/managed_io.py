"""Adapter-owned outputs: no-follow paths, provenance checks and atomic files."""
import os
import re
import secrets
import stat

HEADER = "# Auto-generated by tools/adapters/claude-code.sh — DO NOT EDIT (source: hooks.yaml)"
COMPILED = "hooks/.compiled.env"
SETTINGS = ".claude/settings.json"


class ManagedOutputs:
    def __init__(self, root):
        self.root = os.path.abspath(root)
        try:
            self.fd = os.open(self.root, os.O_RDONLY | os.O_DIRECTORY | os.O_NOFOLLOW)
        except OSError as error:
            raise SystemExit(f"unsafe managed target root: {error}")

    def close(self):
        os.close(self.fd)

    def parent(self, relative, create=False):
        parts = relative.split("/")
        if not parts or any(part in ("", ".", "..") for part in parts):
            raise SystemExit("unsafe managed path")
        fd = os.dup(self.fd)
        try:
            for part in parts[:-1]:
                try:
                    child = os.open(part, os.O_RDONLY | os.O_DIRECTORY | os.O_NOFOLLOW, dir_fd=fd)
                except FileNotFoundError:
                    if not create:
                        os.close(fd)
                        return None, parts[-1]
                    os.mkdir(part, dir_fd=fd)
                    child = os.open(part, os.O_RDONLY | os.O_DIRECTORY | os.O_NOFOLLOW, dir_fd=fd)
                os.close(fd)
                fd = child
            return fd, parts[-1]
        except OSError as error:
            os.close(fd)
            raise SystemExit(f"unsafe managed output ancestor ({relative}): {error}")

    def read(self, relative):
        fd, name = self.parent(relative)
        if fd is None:
            return None
        try:
            try:
                mode = os.stat(name, dir_fd=fd, follow_symlinks=False)
            except FileNotFoundError:
                return None
            if not stat.S_ISREG(mode.st_mode) or mode.st_nlink != 1:
                raise SystemExit(f"unsafe managed output; user object preserved: {relative}")
            child = os.open(name, os.O_RDONLY | os.O_NOFOLLOW | os.O_NONBLOCK, dir_fd=fd)
            with os.fdopen(child, "rb") as stream:
                actual = os.fstat(stream.fileno())
                if (actual.st_dev, actual.st_ino) != (mode.st_dev, mode.st_ino):
                    raise SystemExit("managed output changed during read")
                data = stream.read()
            return data
        finally:
            os.close(fd)

    def validate(self):
        for relative in (".claude/skills/.probe", "hooks/.probe"):
            fd, _ = self.parent(relative)
            if fd is not None:
                os.close(fd)
        files = {relative: self.read(relative) for relative in (SETTINGS, COMPILED)}
        compiled = files[COMPILED]
        if compiled is not None:
            lines = compiled.decode("utf-8").splitlines()
            names = ("KB_PROTECT_PATHS", "DENY_PATTERNS", "DENY_MESSAGE", "DENY_KB_MESSAGE")
            if len(lines) != 5 or lines[0] != HEADER or any(
                re.fullmatch(name + r"='(?:[^']|'\\'')*'", line) is None
                for name, line in zip(names, lines[1:])
            ):
                raise SystemExit("unowned compiled policy preserved; refusing mutation")
        return files

    def write_many(self, files, expected=None):
        before = self.validate()
        if expected is not None and before != expected:
            raise SystemExit("managed inputs changed; refusing replacement")
        staged = []
        try:
            for relative, data in files.items():
                if data == before[relative]:
                    continue
                fd, name = self.parent(relative, create=True)
                temporary = "." + name + ".sdd-" + secrets.token_hex(12)
                staged.append((fd, name, temporary, relative))
                child = os.open(temporary, os.O_WRONLY | os.O_CREAT | os.O_EXCL | os.O_NOFOLLOW, 0o600, dir_fd=fd)
                with os.fdopen(child, "wb") as stream:
                    if before[relative] is not None:
                        prior = os.stat(name, dir_fd=fd, follow_symlinks=False)
                        os.fchmod(stream.fileno(), stat.S_IMODE(prior.st_mode))
                    stream.write(data)
                    stream.flush()
                    os.fsync(stream.fileno())
            if self.validate() != before:
                raise SystemExit("managed outputs changed; refusing replacement")
            for fd, name, temporary, relative in staged:
                if before[relative] is None:
                    # Linking a staged regular file never replaces a newly added user object.
                    os.link(temporary, name, src_dir_fd=fd, dst_dir_fd=fd, follow_symlinks=False)
                    os.unlink(temporary, dir_fd=fd)
                else:
                    os.replace(temporary, name, src_dir_fd=fd, dst_dir_fd=fd)
        finally:
            for fd, _, temporary, _ in staged:
                try:
                    os.unlink(temporary, dir_fd=fd)
                except FileNotFoundError:
                    pass
                os.close(fd)

    def remove_compiled(self):
        if self.validate()[COMPILED] is not None:
            fd, name = self.parent(COMPILED)
            try:
                os.unlink(name, dir_fd=fd)
            finally:
                os.close(fd)

    def check_skill_sources(self, names):
        for name in names:
            if not re.fullmatch(r"[a-z0-9][a-z0-9-]*", name):
                raise SystemExit(f"invalid selected method: {name}")
            fd, file = self.parent(f".agents/skills/{name}/SKILL.md")
            if fd is None:
                raise SystemExit(f"selected method source missing: {name}")
            try:
                if not stat.S_ISREG(os.stat(file, dir_fd=fd, follow_symlinks=False).st_mode):
                    raise SystemExit(f"invalid selected method source: {name}")
            finally:
                os.close(fd)

    def skills(self, names=(), uninstall=False):
        self.validate()
        if not uninstall:
            self.check_skill_sources(names)
            retired_names = [name for name in names if re.match(r"^(sdd-|trinity-|source-command-sdd-)|^superpowers$", name)]
            if retired_names:
                raise SystemExit("retired selected methods refused: " + ", ".join(retired_names))
        fd, _ = self.parent(".claude/skills/.probe", create=not uninstall)
        if fd is None:
            return
        try:
            for name in os.listdir(fd):
                own = "../../.agents/skills/" + name
                info = os.stat(name, dir_fd=fd, follow_symlinks=False)
                ours = stat.S_ISLNK(info.st_mode) and os.readlink(name, dir_fd=fd) == own
                retired = re.match(r"^(sdd-|trinity-|source-command-sdd-)|^superpowers$", name)
                if not uninstall and retired and not ours:
                    raise SystemExit(f"retired method changed after preflight; user entry preserved: {name}")
                if ours and (uninstall or retired):
                    os.unlink(name, dir_fd=fd)
                    print(f"removed exact adapter-owned skill link: {name} -> {own}")
            if not uninstall:
                for name in names:
                    own = "../../.agents/skills/" + name
                    try:
                        info = os.stat(name, dir_fd=fd, follow_symlinks=False)
                    except FileNotFoundError:
                        os.symlink(own, name, dir_fd=fd)
                        continue
                    if not stat.S_ISLNK(info.st_mode) or os.readlink(name, dir_fd=fd) != own:
                        raise SystemExit(f"unowned selected method preserved: {name}")
        finally:
            os.close(fd)
